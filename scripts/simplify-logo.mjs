import { writeFileSync } from 'node:fs';
import { LOGO_SHAPES } from '../src/components/BrandLogo/logoShapes.js';
// Ramer-Douglas-Peucker: retain silhouette corners while removing redundant samples.
const tolerance = 0.002;
function distanceSquared(p, a, b) {
 const dx=b[0]-a[0], dy=b[1]-a[1];
 const t=dx||dy ? Math.max(0,Math.min(1,((p[0]-a[0])*dx+(p[1]-a[1])*dy)/(dx*dx+dy*dy))) : 0;
 return (p[0]-a[0]-t*dx)**2+(p[1]-a[1]-t*dy)**2;
}
function simplify(points) {
 let max=tolerance*tolerance, split=-1;
 for(let i=1;i<points.length-1;i++) {
  const d=distanceSquared(points[i],points[0],points.at(-1));
  if(d>max){max=d;split=i;}
 }
 if(split<0)return [points[0],points.at(-1)];
 return [...simplify(points.slice(0,split+1)).slice(0,-1),...simplify(points.slice(split))];
}
const shapes=LOGO_SHAPES.map(points=>{
 let split=1;
 for(let i=2;i<points.length;i++)if(distanceSquared(points[i],points[0],points[0])>distanceSquared(points[split],points[0],points[0]))split=i;
 return [...simplify(points.slice(0,split+1)).slice(0,-1),...simplify([...points.slice(split),points[0]]).slice(0,-1)];
});
writeFileSync(new URL('../src/components/BrandLogo/extrusionShapes.js',import.meta.url), '// Generated by scripts/simplify-logo.mjs; maximum outline error 0.002 logo units.\nexport const LOGO_SHAPES = '+JSON.stringify(shapes)+';\n');
console.log('Outline vertices:',LOGO_SHAPES.map(p=>p.length),'->',shapes.map(p=>p.length));
